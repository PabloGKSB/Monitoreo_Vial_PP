"""Inspect an application snapshot, or restore into a new disposable target.

This restores vial tables and originals, never Supabase Auth, roles or secrets.
The CLI never loads .env and defaults to inspection without connecting to a DB.
"""

import argparse
from datetime import datetime
from hashlib import file_digest
import json
import os
from pathlib import Path
import shutil
import stat
from uuid import UUID
from zipfile import ZipFile

from sqlalchemy import DateTime, Uuid, func, select, text

from src.database import database_engine, users, trips, jobs, observations

TABLES = (users, trips, jobs, observations)
MAX_JSON_BYTES = 64 * 1024 * 1024
MAX_ORIGINAL_BYTES = 64 * 1024 * 1024
MAX_TOTAL_BYTES = 4 * 1024 * 1024 * 1024


def _json(archive, name):
    if archive.getinfo(name).file_size > MAX_JSON_BYTES:
        raise ValueError('Metadatos del respaldo demasiado grandes')
    return json.loads(archive.read(name))


def inspect_snapshot(snapshot):
    """Validate structure, typed rows and every original before any target write."""
    with ZipFile(snapshot) as archive:
        entries = archive.infolist()
        names = [entry.filename for entry in entries]
        if len(names) != len(set(names)) or any(stat.S_ISLNK(entry.external_attr >> 16) for entry in entries):
            raise ValueError('El respaldo contiene duplicados o enlaces simbolicos')
        if sum(entry.file_size for entry in entries) > MAX_TOTAL_BYTES:
            raise ValueError('Respaldo superior al limite de restauracion de 4 GiB')
        manifest = _json(archive, 'manifest.json')
        records = _json(archive, 'records.json')
        if manifest.get('version') != 'vial-backup-1' or manifest.get('schema_revision') != '0002_backend_role':
            raise ValueError('Version de respaldo o esquema no admitida')
        if set(records) != {table.name for table in TABLES}:
            raise ValueError('El respaldo no contiene las cuatro tablas esperadas')
        counts = {name: len(rows) for name, rows in records.items()}
        if counts != manifest.get('counts') or manifest.get('missing_originals') != []:
            raise ValueError('Conteos inconsistentes u originales faltantes')
        # Only explicit model columns may be inserted; geom is generated by PostgreSQL.
        for table in TABLES:
            columns = {column.name: column for column in table.columns}
            identifiers = set()
            for row in records[table.name]:
                if set(row) != set(columns):
                    raise ValueError('Columnas no admitidas o faltantes en el respaldo')
                for key, value in row.items():
                    if value is None:
                        continue
                    if isinstance(columns[key].type, Uuid):
                        row[key] = UUID(value)
                    elif isinstance(columns[key].type, DateTime):
                        row[key] = datetime.fromisoformat(value)
                        if row[key].tzinfo is None:
                            raise ValueError('Las fechas del respaldo deben incluir zona horaria')
                if row['id'] in identifiers:
                    raise ValueError('Identificadores de filas duplicados')
                identifiers.add(row['id'])
        originals = manifest.get('originals', {})
        job_ids = {str(row['id']) for row in records['jobs']}
        if set(originals) != job_ids:
            raise ValueError('Los originales no corresponden a los trabajos')
        expected = {'manifest.json', 'records.json'} | {'archives/' + identifier + '/input.zip' for identifier in job_ids}
        if set(names) != expected:
            raise ValueError('Archivos inesperados, rutas inseguras u originales ausentes')
        for row in records['jobs']:
            if row['status'] not in {'COMPLETED', 'FAILED'}:
                raise ValueError('No restaurar trabajos pendientes o en procesamiento')
            identifier = str(row['id'])
            name = 'archives/' + identifier + '/input.zip'
            size = archive.getinfo(name).file_size
            if not 0 < size <= MAX_ORIGINAL_BYTES or size != row['upload_bytes']:
                raise ValueError('Tamano del original inconsistente o fuera del limite')
            with archive.open(name) as source:
                digest = file_digest(source, 'sha256').hexdigest()
            if digest != row['sha256'] or digest != originals[identifier]:
                raise ValueError('El original no coincide con su SHA-256')
    return manifest, records


def restore(engine, snapshot, destination):
    """Insert into empty tables and a new directory; refuse the active DB name.

    Caller must stop every writer. PostgreSQL destinations are restricted to
    vial_restore_* databases. SQLite is accepted only for isolated unit tests.
    No migration, CREATE DATABASE, DROP, TRUNCATE or overwrite is performed.
    """
    if engine.dialect.name == 'postgresql' and not (engine.url.database or '').startswith('vial_restore_'):
        raise ValueError('La base destino debe ser descartable y llamarse vial_restore_*')
    destination = Path(destination).absolute()
    if destination.exists() or any(path.is_symlink() for path in (destination, *destination.parents)):
        raise ValueError('El directorio destino debe ser nuevo y no contener enlaces')
    manifest, records = inspect_snapshot(snapshot)
    created_files, created_directories = [], []
    try:
        with engine.begin() as connection:
            if engine.dialect.name == 'postgresql':
                if connection.scalar(text('SELECT version_num FROM public.alembic_version')) != '0002_backend_role':
                    raise ValueError('Aplicar las revisiones esperadas en la base descartable')
                connection.exec_driver_sql('LOCK TABLE vial.users, vial.trips, vial.jobs, vial.observations IN ACCESS EXCLUSIVE MODE NOWAIT')
            if any(connection.scalar(select(func.count()).select_from(table)) for table in TABLES):
                raise ValueError('La base destino debe estar vacia; no se sobrescriben datos')
            destination.mkdir()
            created_directories.append(destination)
            with ZipFile(snapshot) as archive:
                for identifier in manifest['originals']:
                    directory = destination / identifier
                    directory.mkdir()
                    created_directories.append(directory)
                    path = directory / 'input.zip'
                    with path.open('xb') as output:
                        created_files.append(path)
                        with archive.open('archives/' + identifier + '/input.zip') as source:
                            shutil.copyfileobj(source, output, length=1024 * 1024)
                    with path.open('rb') as source:
                        if file_digest(source, 'sha256').hexdigest() != manifest['originals'][identifier]:
                            raise ValueError('La copia restaurada no conserva el hash')
            for table in TABLES:
                # Individual inserts retain JSON nulls and heterogeneous nullable values.
                for row in records[table.name]:
                    connection.execute(table.insert().values(**row))
                if connection.scalar(select(func.count()).select_from(table)) != manifest['counts'][table.name]:
                    raise ValueError('El conteo restaurado no coincide')
    except Exception:
        # Remove only files/directories created by this call, never a preexisting tree.
        for path in reversed(created_files):
            path.unlink()
        for path in reversed(created_directories):
            path.rmdir()
        raise
    return {'counts': manifest['counts'], 'originals': len(manifest['originals']),
            'crc_and_sha256_verified': True, 'auth_restored': False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('snapshot', type=Path)
    parser.add_argument('--target', type=Path)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--confirm-disposable', action='store_true')
    args = parser.parse_args()
    engine = None
    try:
        if not args.apply:
            manifest, _ = inspect_snapshot(args.snapshot)
            print(json.dumps({'mode': 'inspect', 'counts': manifest['counts'],
                              'originals': len(manifest['originals']), 'auth_restored': False}))
            return 0
        if not args.confirm_disposable or args.target is None:
            parser.error('--apply requiere --confirm-disposable y --target nuevo')
        # No fallback to VIAL_DATABASE_URL, .env or a migration/admin connection.
        engine = database_engine(os.environ['VIAL_RESTORE_DATABASE_URL'])
        print(json.dumps({'mode': 'restore', **restore(engine, args.snapshot, args.target)}))
        return 0
    except Exception as error:
        print(json.dumps({'error_type': type(error).__name__, 'details_withheld': True}))
        return 1
    finally:
        if engine is not None:
            engine.dispose()


if __name__ == '__main__':
    raise SystemExit(main())
